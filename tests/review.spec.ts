import {test,expect} from '@playwright/test';
test('review, persistence, filters, notes, navigation and export',async({page})=>{
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Every detail. In perspective.'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Accept',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Accept',exact:true}).click();
 await page.getByLabel('Reviewer note').fill('Discuss mutual termination with counsel.');
 await expect(page.getByText('1 of 24 reviewed')).toBeVisible();
 await page.reload();
 await expect(page.getByLabel('Reviewer note')).toHaveValue('Discuss mutual termination with counsel.');
 await expect(page.getByRole('button',{name:'Accept',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.getByLabel('Filter severity').selectOption('low');
 await expect(page.getByText('4 of 24 findings')).toBeVisible();
 await page.getByLabel('Search findings').fill('unmatchable-search');
 await expect(page.getByText('No matching findings')).toBeVisible();
 await page.getByRole('button',{name:'Clear filters'}).click();
 await page.getByRole('button',{name:'View f-05:',exact:false}).click();
 await expect(page.getByRole('heading',{name:'Unrestricted use of derived data',exact:true})).toHaveCount(2);
 await page.getByRole('button',{name:'Dismiss',exact:true}).click();
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export review'}).click();
 expect((await download).suggestedFilename()).toBe('northwind-contract-review.json');
});
