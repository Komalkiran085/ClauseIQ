 await expect(page.locator('.paper ins')).toContainText('Either Party may terminate');
 await expect(page.getByText('0 of 24 reviewed')).toBeVisible();
 await page.reload();
 await expect(page.getByRole('button',{name:'Undo suggested edit'})).toBeVisible();
 await page.getByRole('button',{name:'Undo suggested edit'}).click();
